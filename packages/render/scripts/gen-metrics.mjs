// Generates src/metrics.ts: per-character advance widths (1/1000 em) of the PDF base-14 fonts,
// taken from jsPDF's built-in AFM metrics. Helvetica ≈ Arial, Times ≈ Times New Roman, Courier.
import { jsPDF } from 'jspdf';
import { writeFileSync } from 'node:fs';

const doc = new jsPDF({ unit: 'pt' });
const fonts = { sans: 'helvetica', serif: 'times', mono: 'courier' };
const out = {};
for (const [key, name] of Object.entries(fonts)) {
  for (const style of ['normal', 'bold']) {
    doc.setFont(name, style);
    const widths = [];
    for (let c = 32; c < 256; c++) widths.push(Math.round(doc.getStringUnitWidth(String.fromCharCode(c)) * 1000));
    out[`${key}-${style}`] = widths;
  }
}
const body = Object.entries(out).map(([k, v]) => `  '${k}': [${v.join(',')}],`).join('\n');
writeFileSync(
  new URL('../src/metrics.ts', import.meta.url),
  `// Generated by scripts/gen-metrics.mjs — do not edit.\n// Advance widths in 1/1000 em for char codes 32..255.\nexport const METRICS: Record<string, number[]> = {\n${body}\n};\n`,
);
console.log('ok');
